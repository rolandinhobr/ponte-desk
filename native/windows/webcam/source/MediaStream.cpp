HRESULT MediaStream::Initialize(IMFMediaSource* source, int index)
{
	RETURN_HR_IF_NULL(E_POINTER, source);
	_source = source;
	_index = index;

	RETURN_IF_FAILED(SetGUID(MF_DEVICESTREAM_STREAM_CATEGORY, PINNAME_VIDEO_CAPTURE));
	RETURN_IF_FAILED(SetUINT32(MF_DEVICESTREAM_STREAM_ID, index));
	RETURN_IF_FAILED(SetUINT32(MF_DEVICESTREAM_FRAMESERVER_SHARED, 1));
	RETURN_IF_FAILED(SetUINT32(MF_DEVICESTREAM_ATTRIBUTE_FRAMESOURCE_TYPES, MFFrameSourceTypes::MFFrameSourceTypes_Color));

	RETURN_IF_FAILED(MFCreateEventQueue(&_queue));
	RETURN_IF_FAILED(_generator.EnsureRenderTarget(1920, 1080));


    auto types=wil::make_unique_cotaskmem_array<wil::com_ptr_nothrow<IMFMediaType>>(4);
    const UINT widths[]={1920,1920,1280,1280};
    const UINT heights[]={1080,1080,720,720};
    for(UINT i=0;i<4;++i){
        bool nv12=(i%2)==0;wil::com_ptr_nothrow<IMFMediaType> media;
        RETURN_IF_FAILED(MFCreateMediaType(&media));
        RETURN_IF_FAILED(media->SetGUID(MF_MT_MAJOR_TYPE,MFMediaType_Video));
        RETURN_IF_FAILED(media->SetGUID(MF_MT_SUBTYPE,nv12?MFVideoFormat_NV12:MFVideoFormat_RGB32));
        RETURN_IF_FAILED(MFSetAttributeSize(media.get(),MF_MT_FRAME_SIZE,widths[i],heights[i]));
        RETURN_IF_FAILED(media->SetUINT32(MF_MT_DEFAULT_STRIDE,widths[i]*(nv12?1:4)));
        RETURN_IF_FAILED(media->SetUINT32(MF_MT_INTERLACE_MODE,MFVideoInterlace_Progressive));
        RETURN_IF_FAILED(media->SetUINT32(MF_MT_ALL_SAMPLES_INDEPENDENT,TRUE));
        RETURN_IF_FAILED(MFSetAttributeRatio(media.get(),MF_MT_FRAME_RATE,30,1));
        RETURN_IF_FAILED(MFSetAttributeRatio(media.get(),MF_MT_PIXEL_ASPECT_RATIO,1,1));
        RETURN_IF_FAILED(media->SetUINT32(MF_MT_AVG_BITRATE,widths[i]*heights[i]*(nv12?12:32)*30));
        types[i]=media.detach();
    }

	RETURN_IF_FAILED_MSG(MFCreateStreamDescriptor(_index, (DWORD)types.size(), types.get(), &_descriptor), "MFCreateStreamDescriptor failed");

	wil::com_ptr_nothrow<IMFMediaTypeHandler> handler;
	RETURN_IF_FAILED(_descriptor->GetMediaTypeHandler(&handler));
	TraceMFAttributes(handler.get(), L"MediaTypeHandler");
	RETURN_IF_FAILED(handler->SetCurrentMediaType(types[0]));

	return S_OK;
}

HRESULT MediaStream::Start(IMFMediaType* type)
{
	RETURN_HR_IF(MF_E_SHUTDOWN, !_queue || !_allocator);


    wil::com_ptr_nothrow<IMFMediaType> selected=type;
    wil::com_ptr_nothrow<IMFMediaTypeHandler> handler;
    RETURN_IF_FAILED(_descriptor->GetMediaTypeHandler(&handler));
    if(!selected)RETURN_IF_FAILED(handler->GetCurrentMediaType(&selected));
    UINT width=0,height=0,numerator=0,denominator=0;
    RETURN_IF_FAILED(selected->GetGUID(MF_MT_SUBTYPE,&_format));
    RETURN_IF_FAILED(MFGetAttributeSize(selected.get(),MF_MT_FRAME_SIZE,&width,&height));
    RETURN_IF_FAILED(MFGetAttributeRatio(selected.get(),MF_MT_FRAME_RATE,&numerator,&denominator));
    RETURN_HR_IF(MF_E_INVALIDMEDIATYPE,!((width==1280&&height==720)||(width==1920&&height==1080))||!denominator||numerator!=30*denominator||(_format!=MFVideoFormat_NV12&&_format!=MFVideoFormat_RGB32));
    RETURN_IF_FAILED(handler->SetCurrentMediaType(selected.get()));
    RETURN_IF_FAILED(_generator.EnsureRenderTarget(width,height));

	RETURN_IF_FAILED(_allocator->InitializeSampleAllocator(10, selected.get()));
	RETURN_IF_FAILED(_queue->QueueEventParamVar(MEStreamStarted, GUID_NULL, S_OK, nullptr));
	_state = MF_STREAM_STATE_RUNNING;
	return S_OK;
}

HRESULT MediaStream::Stop()
{
	RETURN_HR_IF(MF_E_SHUTDOWN, !_queue || !_allocator);

	RETURN_IF_FAILED(_allocator->UninitializeSampleAllocator());
	RETURN_IF_FAILED(_queue->QueueEventParamVar(MEStreamStopped, GUID_NULL, S_OK, nullptr));
	_state = MF_STREAM_STATE_STOPPED;
	return S_OK;
}

